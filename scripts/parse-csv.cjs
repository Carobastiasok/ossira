function parseCSVLine(line) {
  const result = [];
  let current = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === '"') {
      inQuotes = !inQuotes;
    } else if (char === ',' && !inQuotes) {
      result.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  result.push(current.trim());
  return result;
}

const typologyMap = {
  '94': 'CALZADOS',
  '00': 'REMERAS',
  '10': 'CAMISAS',
  '40': 'JEAN',
  '20': 'VESTIDOS',
  '41': 'PANTALON (NO JEAN)',
  '60': 'ABRIGOS',
  '70': 'ABRIGOS',
  '82': 'ABRIGOS'
};

const lines = rawCsv.split('\n').filter(l => l.trim().length > 0);
const headers = parseCSVLine(lines[0]);
console.log('Headers:', headers);

const items = [];

for (let i = 1; i < lines.length; i++) {
  const cols = parseCSVLine(lines[i]);
  const code = cols[0] ? cols[0].replace(/"/g, '').trim() : '';
  if (!code || code.length < 5) continue; // Skip separator lines like ",,,,,,0%,,"

  const season = code.length >= 2 ? code.substring(0, 2) : (cols[1] || '');
  const typologyCode = code.length >= 4 ? code.substring(2, 4) : (cols[2] || '');
  const model = code.length >= 7 ? code.substring(4, 7) : (cols[4] || '');
  
  const mappedTypology = typologyMap[typologyCode] || 'OTRO';
  const declaredTypology = cols[3] || mappedTypology;
  const typology = declaredTypology || mappedTypology;

  const rawOrigPrice = cols[5] ? cols[5].replace(/"/g, '').trim() : '';
  const rawDiscount = cols[6] ? cols[6].replace(/"/g, '').replace('%', '').trim() : '0';
  const discountPercent = parseInt(rawDiscount, 10) || 0;

  let origPriceNum = null;
  if (rawOrigPrice) {
    // E.g. "$39.900,00" -> 39900
    const clean = rawOrigPrice.replace('$', '').replace(/\./g, '').replace(',', '.').trim();
    origPriceNum = parseFloat(clean) || null;
  }

  let finalPriceNum = null;
  let finalPriceFormatted = '';
  if (origPriceNum !== null) {
    finalPriceNum = Math.round(origPriceNum * (1 - (discountPercent / 100)));
    finalPriceFormatted = '$' + finalPriceNum.toLocaleString('es-AR') + ',00';
  } else if (cols[7] && cols[7].trim()) {
    finalPriceFormatted = cols[7].replace(/"/g, '').trim();
  }

  const observations = cols[8] ? cols[8].replace(/"/g, '').trim() : '';

  items.push({
    code,
    season,
    typologyCode,
    typology,
    model,
    originalPrice: rawOrigPrice || null,
    originalPriceNum: origPriceNum,
    discountPercent,
    finalPrice: finalPriceFormatted || null,
    finalPriceNum: finalPriceNum,
    observations
  });
}

console.log('Total valid items parsed:', items.length);
fs.writeFileSync('src/data-parsed.json', JSON.stringify(items, null, 2));
console.log('Done');
